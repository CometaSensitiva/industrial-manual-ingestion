export type Lang = "en" | "it";
export const LANGS: Lang[] = ["en", "it"];
const dictionaries: Record<Lang, Record<Key, string>> = { en, it };
const STORAGE = "manual-ingestion-lang";

export const LangContext = createContext<Lang>("en");

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  return (key, vars) =>
    (dictionaries[lang][key] ?? en[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));
}

export function useT(): T {
  return translator(useContext(LangContext));
}

/** `?lang=` first, then the remembered choice, then the browser language. */
export function detectLang(): Lang {
  if (typeof window === "undefined") return "en";
  const param = new URLSearchParams(window.location.search).get("lang");
  if (param === "it" || param === "en") return param;
  try {
    const saved = window.localStorage.getItem(STORAGE);
    if (saved === "it" || saved === "en") return saved;
  } catch {
    // Storage can be unavailable (private mode); fall through to the browser.
  }
  return window.navigator.language?.toLowerCase().startsWith("it") ? "it" : "en";
}

export function rememberLang(lang: Lang): void {
  try {
    window.localStorage.setItem(STORAGE, lang);
  } catch {
    // Not persisting is acceptable.
  }
}

/** Count-aware copy: `count(t, 1, "image1", "images")`. */
export const count = (t: T, n: number, one: Key, many: Key) => (n === 1 ? t(one) : t(many, { n }));
